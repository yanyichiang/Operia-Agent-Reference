/**
 * H-C0 / H-C1 — Internal Service Route Registry.
 *
 * Machine-readable inventory of `/service/*` routes. H-C1 wires the Memory
 * Control vertical slice into enforcement via `src/security/credentials.ts`.
 */

export type CallerEvidence = "confirmed" | "planned" | "external";

export type InternalServiceCaller = {
  sourceDomain: string;
  serviceId: string;
  evidence: CallerEvidence;
  sourcePath?: string;
};

export type DeploymentTarget =
  | "memory"
  | "agent"
  | "tgbot"
  | "health"
  | "think-gate-d-canary"
  | string;

export type InternalServiceRoute = {
  id: string;
  deploymentTarget: DeploymentTarget;
  host: string;
  path: string;
  methods: string[];
  credentialClass: "internal_service" | "domain_session" | "application_api";
  credentialEnv?: string;
  callers: InternalServiceCaller[];
  /**
   * A bearer-less internal route is still an internal route: it is reachable
   * only on the internal hostname. This flag marks the exception explicitly so
   * it is not confused with a public route.
   */
  bearerlessInternalException?: boolean;
};

