/**
 * Registry helpers used by H-C1 enforcement and tests.
 */

export function internalServiceRouteKey(route: InternalServiceRoute): string {
  return [route.deploymentTarget, route.host, route.path, route.methods.join(",")].join("|");
}

export function findInternalServiceRoutesByPrefix(
  routes: InternalServiceRoute[],
  host: string,
  pathnamePrefix: string,
): InternalServiceRoute[] {
  return routes.filter((route) => route.host === host && route.path.startsWith(pathnamePrefix));
}

export function findMemoryControlRoutes(routes: InternalServiceRoute[] = INTERNAL_SERVICE_ROUTES): InternalServiceRoute[] {
  return routes.filter(
    (route) =>
      route.deploymentTarget === "memory" &&
      route.credentialClass === "internal_service" &&
      route.credentialEnv === "MEMORY_CONTROL_SERVICE_BEARER" &&
      route.path.startsWith("/service/control/"),
  );
}

export function getConfirmedCallers(route: InternalServiceRoute): InternalServiceCaller[] {
  return route.callers.filter((caller) => caller.evidence === "confirmed");
}
